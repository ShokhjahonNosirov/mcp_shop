def top_products(
    db: Database,
    period: models.Period,
    ranked_by: Literal["revenue", "units"],
    category: str | None,
    limit: int,
) -> models.TopProducts:
    days = PERIOD_DAYS[period]
    since = datetime.now(UTC) - timedelta(days=days) if days is not None else None
    order_column = "revenue" if ranked_by == "revenue" else "units_sold"

    query = sql.SQL(
        """
        SELECT p.id AS product_id, p.sku, p.name, p.category,
               sum(oi.quantity) AS units_sold,
               sum(oi.quantity * oi.unit_price) AS revenue
        FROM shop.order_items oi
        JOIN shop.orders o   ON o.id = oi.order_id
        JOIN shop.products p ON p.id = oi.product_id
        WHERE o.status = ANY (%(revenue_statuses)s)
          AND (%(since)s::timestamptz IS NULL OR o.ordered_at >= %(since)s::timestamptz)
          AND (%(category)s::text IS NULL OR lower(p.category) = lower(%(category)s::text))
        GROUP BY p.id
        ORDER BY {order_column} DESC, p.id
        """
    ).format(order_column=sql.Identifier(order_column))
    result = db.fetch(
        query,
        {"revenue_statuses": REVENUE_STATUSES, "since": since, "category": category},
        max_rows=limit,
    )

    if category is not None and not result.rows:
        known = [row["category"] for row in db.fetch("SELECT DISTINCT category FROM shop.products ORDER BY 1").rows]
        if category.lower() not in (k.lower() for k in known):
            raise NotFoundError(f"Unknown category {category!r}. Known categories: {', '.join(known)}.")

    return models.TopProducts(
        period=period,
        since=since,
        ranked_by=ranked_by,
        category=category,
        products=[models.ProductSales(rank=i, **row) for i, row in enumerate(result.rows, start=1)],
    )


def revenue_summary(
    db: Database,
    start_date: date,
    end_date: date,
    group_by: Literal["none", "day", "week", "month", "quarter"],
) -> models.RevenueSummary:
    if end_date < start_date:
        raise RequestError(f"end_date ({end_date}) is before start_date ({start_date}).")

    # end_date is inclusive: count everything before the next midnight (UTC).
    params = {
        "start": start_date,
        "end": end_date,
        "revenue_statuses": REVENUE_STATUSES,
        "grain": group_by,
    }
    in_range = "o.ordered_at >= %(start)s::date AND o.ordered_at < %(end)s::date + 1"

    totals = db.fetch(
        """
        WITH order_totals AS (
            SELECT o.id, o.customer_id, o.status, sum(oi.quantity * oi.unit_price) AS total
            FROM shop.orders o
            JOIN shop.order_items oi ON oi.order_id = o.id
            WHERE """
        + in_range
        + """
            GROUP BY o.id
        )
        SELECT coalesce(sum(total) FILTER (WHERE status = ANY (%(revenue_statuses)s)), 0) AS revenue,
               count(*) FILTER (WHERE status = ANY (%(revenue_statuses)s)) AS orders,
               count(DISTINCT customer_id) FILTER (WHERE status = ANY (%(revenue_statuses)s)) AS customers,
               count(*) FILTER (WHERE status = 'cancelled') AS cancelled_orders,
               count(*) FILTER (WHERE status = 'refunded') AS refunded_orders
        FROM order_totals
        """,
        params,
    ).rows[0]

    breakdown: list[models.RevenuePeriod] = []
    breakdown_truncated = False
    if group_by != "none":
        result = db.fetch(
            """
            SELECT date_trunc(%(grain)s, o.ordered_at)::date AS period_start,
                   sum(oi.quantity * oi.unit_price) AS revenue,
                   count(DISTINCT o.id) AS orders
            FROM shop.orders o
            JOIN shop.order_items oi ON oi.order_id = o.id
            WHERE o.status = ANY (%(revenue_statuses)s) AND """
            + in_range
            + """
            GROUP BY 1
            ORDER BY 1
            """,
            params,
        )
        breakdown = [models.RevenuePeriod(**row) for row in result.rows]
        breakdown_truncated = result.truncated

    revenue: Decimal = totals["revenue"]
    average = (revenue / totals["orders"]).quantize(Decimal("0.01")) if totals["orders"] else None
    return models.RevenueSummary(
        start_date=start_date,
        end_date=end_date,
        average_order_value=average,
        group_by=group_by,
        breakdown=breakdown,
        breakdown_truncated=breakdown_truncated,
        **totals,
    )


# Free-form SQL -------------------------------------------------------------


def run_select_query(db: Database, query: str, max_rows: int) -> models.QueryRows:
    checked = validate_select(query)
    # LiteralString cannot express "validated at runtime"; the cast documents
    # that this is the one place agent-written SQL reaches the database.
    result = db.fetch(cast(LiteralString, checked), max_rows=max_rows)
    return models.QueryRows(
        columns=result.columns,
        rows=result.rows,
        row_count=len(result.rows),
        truncated=result.truncated,
    )


def _escape_like(text: str) -> str:
    """Make %, _ and \\ match literally inside an ILIKE pattern."""
    return text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
