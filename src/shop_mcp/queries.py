"""Domain queries behind the tools.

Plain functions that take a Database and return models. They know nothing
about MCP, so they can be tested and reused on their own. All values are
passed as bound parameters; the one dynamic identifier (the sort column) is
composed with psycopg.sql.Identifier from a fixed set of names.
"""

from datetime import UTC, date, datetime, timedelta
from decimal import Decimal
from typing import Literal, LiteralString, cast

from psycopg import sql

from shop_mcp import models
from shop_mcp.db import Database
from shop_mcp.sql_guard import validate_select

# Orders that count as revenue. Pending orders are not paid yet; cancelled
# and refunded ones were never or are no longer money in the bank.
REVENUE_STATUSES = ["paid", "shipped", "delivered"]

PERIOD_DAYS: dict[models.Period, int | None] = {
    "last_7_days": 7,
    "last_30_days": 30,
    "last_90_days": 90,
    "last_365_days": 365,
    "all_time": None,
}

# Tables (and views) in the shop schema that the connected role may read.
# has_table_privilege makes discovery reflect the real grants.
_VISIBLE_RELATIONS = """
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'shop'
      AND c.relkind IN ('r', 'p', 'v', 'm')
      AND has_table_privilege(c.oid, 'SELECT')
"""


class RequestError(Exception):
    """The request cannot be answered as asked. The message is for the agent."""


class NotFoundError(RequestError):
    """The requested entity does not exist."""


# Schema discovery ----------------------------------------------------------


def list_tables(db: Database) -> models.TableList:
    result = db.fetch(
        "SELECT c.relname AS name,"
        "       obj_description(c.oid, 'pg_class') AS description,"
        "       greatest(c.reltuples, 0)::bigint AS approximate_rows"
        + _VISIBLE_RELATIONS
        + " ORDER BY c.relname"
    )
    return models.TableList(tables=[models.TableSummary(**row) for row in result.rows])


def describe_table(db: Database, table_name: str) -> models.TableDescription:
    found = db.fetch(
        "SELECT c.oid, c.relname AS name, obj_description(c.oid, 'pg_class') AS description"
        + _VISIBLE_RELATIONS
        + " AND c.relname = %(name)s",
        {"name": table_name},
    )
    if not found.rows:
        available = ", ".join(t.name for t in list_tables(db).tables)
        raise NotFoundError(f"Unknown table {table_name!r}. Available tables: {available}.")
    table = found.rows[0]
    params = {"oid": table["oid"]}

    columns = db.fetch(
        """
        SELECT a.attname AS name,
               format_type(a.atttypid, a.atttypmod) AS type,
               NOT a.attnotnull AS nullable,
               CASE a.attidentity
                   WHEN 'a' THEN 'generated always as identity'
                   WHEN 'd' THEN 'generated by default as identity'
                   ELSE pg_get_expr(d.adbin, d.adrelid)
               END AS default,
               EXISTS (
                   SELECT 1 FROM pg_constraint pk
                   WHERE pk.conrelid = a.attrelid AND pk.contype = 'p' AND a.attnum = ANY (pk.conkey)
               ) AS primary_key,
               col_description(a.attrelid, a.attnum) AS description
        FROM pg_attribute a
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = %(oid)s::oid AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY a.attnum
        """,
        params,
    )
    foreign_keys = db.fetch(
        """
        SELECT a.attname AS column, rc.relname AS references_table, ra.attname AS references_column
        FROM pg_constraint con
        CROSS JOIN LATERAL unnest(con.conkey, con.confkey) AS k(col, ref_col)
        JOIN pg_attribute a  ON a.attrelid = con.conrelid AND a.attnum = k.col
        JOIN pg_class rc     ON rc.oid = con.confrelid
        JOIN pg_attribute ra ON ra.attrelid = con.confrelid AND ra.attnum = k.ref_col
        WHERE con.conrelid = %(oid)s::oid AND con.contype = 'f'
        ORDER BY a.attnum
        """,
        params,
    )
    referenced_by = db.fetch(
        """
        SELECT sc.relname AS table, a.attname AS column, ra.attname AS references_column
        FROM pg_constraint con
        CROSS JOIN LATERAL unnest(con.conkey, con.confkey) AS k(col, ref_col)
        JOIN pg_class sc     ON sc.oid = con.conrelid
        JOIN pg_attribute a  ON a.attrelid = con.conrelid AND a.attnum = k.col
        JOIN pg_attribute ra ON ra.attrelid = con.confrelid AND ra.attnum = k.ref_col
        WHERE con.confrelid = %(oid)s::oid AND con.contype = 'f'
          AND has_table_privilege(sc.oid, 'SELECT')
        ORDER BY sc.relname, a.attnum
        """,
        params,
    )
    return models.TableDescription(
        name=table["name"],
        description=table["description"],
        columns=[models.Column(**row) for row in columns.rows],
        foreign_keys=[models.ForeignKey(**row) for row in foreign_keys.rows],
        referenced_by=[models.IncomingReference(**row) for row in referenced_by.rows],
    )


def schema_overview(db: Database) -> str:
    """All visible tables and columns as compact Markdown."""
    lines = ["# shop database schema", ""]
    for table in list_tables(db).tables:
        detail = describe_table(db, table.name)
        lines.append(f"## {detail.name} (~{table.approximate_rows} rows)")
        if detail.description:
            lines.append(detail.description)
        lines.append("")
        fks = {fk.column: f"{fk.references_table}.{fk.references_column}" for fk in detail.foreign_keys}
        for col in detail.columns:
            notes = [n for n in ("PK" if col.primary_key else None, f"-> {fks[col.name]}" if col.name in fks else None) if n]
            line = f"- `{col.name}` {col.type}"
            if notes:
                line += f" ({', '.join(notes)})"
            if col.description:
                line += f": {col.description}"
            lines.append(line)
        lines.append("")
    return "\n".join(lines)


# Customers and orders ------------------------------------------------------


def find_customers(db: Database, search: str, limit: int) -> models.CustomerSearch:
    result = db.fetch(
        """
        SELECT id, full_name, email, country, city, created_at
        FROM shop.customers
        WHERE full_name ILIKE %(pattern)s OR email ILIKE %(pattern)s
        ORDER BY full_name, id
        """,
        {"pattern": f"%{_escape_like(search)}%"},
        max_rows=limit,
    )
    return models.CustomerSearch(
        customers=[models.Customer(**row) for row in result.rows],
        truncated=result.truncated,
    )


def get_customer_orders(
    db: Database,
    customer_id: int,
    status: models.OrderStatus | None,
    limit: int,
) -> models.CustomerOrders:
    customer = db.fetch(
        "SELECT id, full_name, email, country, city, created_at FROM shop.customers WHERE id = %(id)s",
        {"id": customer_id},
    )
    if not customer.rows:
        raise NotFoundError(f"No customer with id {customer_id}. Use find_customers to look up an id by name or email.")

    totals = db.fetch(
        """
        SELECT count(DISTINCT o.id) AS order_count,
               coalesce(sum(oi.quantity * oi.unit_price)
                        FILTER (WHERE o.status = ANY (%(revenue_statuses)s)), 0) AS lifetime_value
        FROM shop.orders o
        JOIN shop.order_items oi ON oi.order_id = o.id
        WHERE o.customer_id = %(id)s
        """,
        {"id": customer_id, "revenue_statuses": REVENUE_STATUSES},
    )
    orders = db.fetch(
        """
        SELECT o.id AS order_id, o.ordered_at, o.status,
               sum(oi.quantity * oi.unit_price) AS total,
               json_agg(json_build_object(
                   'product_id', p.id, 'product_name', p.name,
                   -- as text: a JSON number would round-trip through float
                   'quantity', oi.quantity, 'unit_price', oi.unit_price::text
               ) ORDER BY oi.id) AS items
        FROM shop.orders o
        JOIN shop.order_items oi ON oi.order_id = o.id
        JOIN shop.products p ON p.id = oi.product_id
        WHERE o.customer_id = %(id)s
          AND (%(status)s::text IS NULL OR o.status = %(status)s::text)
        GROUP BY o.id
        ORDER BY o.ordered_at DESC, o.id DESC
        """,
        {"id": customer_id, "status": status},
        max_rows=limit,
    )
    return models.CustomerOrders(
        customer=models.Customer(**customer.rows[0]),
        **totals.rows[0],
        orders=[models.Order(**row) for row in orders.rows],
        truncated=orders.truncated,
    )


